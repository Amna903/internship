"""Exploratory data analysis for the synthetic no-show dataset.

Run:  python -m ml.eda      (writes ml/reports/eda.md)

The report is deterministic (same seed, same data, same text), so it is committed and any change to
the generator shows up as a readable diff. It looks at the data before any model is trained, and
each section ends with what the finding means for the next steps.

Note on scope: this EDA describes the whole dataset, as is usual for a first look. No model is fitted
here. In Step 3 every learned preprocessing value (e.g. the imputation median) is fitted on the
training split only.
"""

import math

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

from . import config
from .data import dataset_hash, generate

REPORT = config.ML_DIR / "reports" / "eda.md"
LEAD_TIME_BUCKETS = [(0, 2), (3, 7), (8, 14), (15, 30), (31, config.LEAD_TIME_MAX_DAYS)]
# A single feature that separates the classes this well is almost always leakage, not insight.
LEAKAGE_AUC = 0.80


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _bar(fraction: float, width: int = 30) -> str:
    return "█" * int(round(fraction * width))


def _table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines)


def _rate_table(df: pd.DataFrame, column, label: str, order=None) -> str:
    grouped = df.groupby(column, observed=True)[config.LABEL].agg(["size", "mean"])
    if order is not None:
        grouped = grouped.reindex(order)
    overall = df[config.LABEL].mean()
    rows = [
        [value, f"{int(r['size']):,}", _pct(r["mean"]), f"{r['mean'] / overall:.2f}×", _bar(r["mean"] / 0.4)]
        for value, r in grouped.iterrows()
    ]
    return _table([label, "rows", "no-show rate", "vs overall", ""], rows)


def two_proportion_p_value(hits_a: int, n_a: int, hits_b: int, n_b: int) -> float:
    """Two-sided z-test: could two rates differ this much by chance alone?"""
    pooled = (hits_a + hits_b) / (n_a + n_b)
    se = math.sqrt(pooled * (1 - pooled) * (1 / n_a + 1 / n_b))
    z = (hits_a / n_a - hits_b / n_b) / se
    return math.erfc(abs(z) / math.sqrt(2))


def lead_time_bucket(days: pd.Series) -> pd.Series:
    labels = [f"{lo}–{hi}" if hi < config.LEAD_TIME_MAX_DAYS else f"{lo}+" for lo, hi in LEAD_TIME_BUCKETS]
    edges = [LEAD_TIME_BUCKETS[0][0] - 1] + [hi for _, hi in LEAD_TIME_BUCKETS]
    return pd.cut(days, bins=edges, labels=labels)


def single_feature_auc(df: pd.DataFrame) -> dict[str, float]:
    """How well each feature alone separates no-shows (0.5 = useless, 1.0 = perfect).

    Categories are scored by their own no-show rate. Missing distances are left out of that feature's
    score. The score is folded so that 0.3 and 0.7 count as equally strong.
    """
    scores = {}
    for feature in config.FEATURES:
        values = df[feature]
        if feature in config.CATEGORICAL_FEATURES or feature in config.BOOLEAN_FEATURES:
            values = values.map(df.groupby(feature)[config.LABEL].mean())
        mask = values.notna()
        auc = roc_auc_score(df.loc[mask, config.LABEL], values[mask].astype(float))
        scores[feature] = max(auc, 1 - auc)
    return scores


def build_report(df: pd.DataFrame) -> str:
    y = df[config.LABEL]
    overall = y.mean()
    per_patient = df.groupby("patient_id").size()
    sections = []

    # ---------------- 1. Basic facts ----------------
    sections.append(
        f"""# Exploratory data analysis: synthetic appointment no-shows

> Synthetic, educational data. Generated by `python -m ml.eda`. Do not edit by hand.

| | |
|---|---|
| Rows (appointments) | {len(df):,} |
| Patients | {per_patient.size:,} |
| Appointments per patient | min {per_patient.min()} · mean {per_patient.mean():.2f} · max {per_patient.max()} |
| Dataset SHA-256 | `{dataset_hash(df)}` |
| Features | {len(config.FEATURES)} ({len(config.NUMERIC_FEATURES)} numeric, {len(config.CATEGORICAL_FEATURES)} categorical, {len(config.BOOLEAN_FEATURES)} boolean) |

## 1. Columns

"""
        + _table(
            ["column", "role", "type", "example"],
            [
                [
                    c,
                    "feature"
                    if c in config.FEATURES
                    else "id (grouping only)"
                    if c in config.ID_COLUMNS
                    else "label"
                    if c == config.LABEL
                    else "oracle (never a feature)",
                    str(df[c].dtype),
                    df[c].iloc[0],
                ]
                for c in df.columns
            ],
        )
    )

    # ---------------- 2. Class balance ----------------
    counts = y.value_counts()
    sections.append(f"""## 2. Class balance

{
        _table(
            ["outcome", "rows", "share", ""],
            [
                ["attended", f"{counts[False]:,}", _pct(1 - overall), _bar(1 - overall)],
                ["no-show", f"{counts[True]:,}", _pct(overall), _bar(overall)],
            ],
        )
    }

**Imbalanced: {_pct(overall)} no-shows.** A model that always says "attends" would be {_pct(1 - overall)}
accurate and completely useless.
→ **Use PR-AUC (minority class), ROC-AUC and the Brier score, not accuracy. Choose the decision
threshold on validation data, not 0.5.**""")

    # ---------------- 3. Missing values ----------------
    missing = df.isna().mean()
    has_distance = df["distance_km"].notna()
    rate_missing = y[~has_distance].mean()
    rate_present = y[has_distance].mean()
    p_missing = two_proportion_p_value(
        int(y[~has_distance].sum()), int((~has_distance).sum()), int(y[has_distance].sum()), int(has_distance.sum())
    )
    missing_verdict = (
        "p < 0.05 would normally count as a real link. But the generator blanks values completely at "
        "random, so here it is a false alarm of the kind a 5% test raises about 1 time in 20: one "
        "significant test is not proof. Either way, the model gets a missing-value flag (below), so it "
        "can use the signal if it is real and will learn to ignore it if not."
        if p_missing < 0.05
        else "Consistent with chance: no evidence that missingness carries signal (the generator blanks at random)."
    )
    sections.append(f"""## 3. Missing values

{_table(["column", "missing", "share"], [[c, f"{int(df[c].isna().sum()):,}", _pct(missing[c])] for c in df.columns if missing[c] > 0])}

All other columns are complete.

Is missingness linked to the outcome? No-show rate with distance **missing {_pct(rate_missing)}**
({(~has_distance).sum():,} rows) vs **present {_pct(rate_present)}**: a gap of
{abs(rate_missing - rate_present) * 100:.1f} points, two-proportion z-test **p = {p_missing:.3f}**.
{missing_verdict}
→ **Step 3: impute `distance_km` with the median of the training split only, and add a
`distance_missing` flag** so the model could still use missingness if it ever carried signal (in real
data it often does).""")

    # ---------------- 4. Numeric features ----------------
    numeric_rows = []
    for feature in config.NUMERIC_FEATURES:
        s = df[feature].dropna()
        numeric_rows.append(
            [
                feature,
                s.min(),
                f"{s.quantile(0.25):g}",
                f"{s.median():g}",
                f"{s.mean():.2f}",
                f"{s.quantile(0.75):g}",
                s.max(),
            ]
        )
    lead = df["lead_time_days"]
    histogram = lead_time_bucket(lead).value_counts(sort=False, normalize=True)
    sections.append(f"""## 4. Numeric features

{_table(["feature", "min", "25%", "median", "mean", "75%", "max"], numeric_rows)}

Lead time distribution:

{_table(["days ahead", "share", ""], [[k, _pct(v), _bar(v)] for k, v in histogram.items()])}

Lead time is **right-skewed**: most bookings are within two weeks, with a long tail.
→ **A log transform is a natural engineered feature.**""")

    # ---------------- 5. Categorical features ----------------
    cat_parts = []
    for feature, order in [
        ("appointment_weekday", config.WEEKDAYS),
        ("age_band", config.AGE_BANDS),
        ("visit_type", config.VISIT_TYPES),
        ("booking_channel", config.BOOKING_CHANNELS),
        ("reminder_sent", [True, False]),
    ]:
        shares = df[feature].value_counts(normalize=True).reindex(order)
        cat_parts.append(f"**{feature}**: " + " · ".join(f"{k} {_pct(v)}" for k, v in shares.items()))
    sections.append(
        "## 5. Categorical features\n\n"
        + "\n\n".join(cat_parts)
        + "\n\nEvery category has enough rows to estimate its effect (smallest: saturday)."
    )

    # ---------------- 6. Feature vs no-show ----------------
    young, old = df.groupby("age_band")[config.LABEL].mean()[["18-24", "55-64"]]
    by_lead = df.groupby(lead_time_bucket(lead), observed=True)[config.LABEL].mean()
    sections.append(f"""## 6. Each feature against the no-show rate

Overall no-show rate: **{_pct(overall)}**. "vs overall" above 1 means riskier than average.

### 6.1 Lead time: a curve, not a straight line

{_rate_table(df, lead_time_bucket(lead), "days ahead")}

The rate climbs steeply over the first days ({_pct(by_lead.iloc[0])} → {_pct(by_lead.iloc[2])} by
8–14 days), then the increase slows down.
→ **A straight-line (linear) effect on raw days misfits this. Engineer `log(1 + lead_time_days)`.**

### 6.2 Reminder × lead time: an interaction

""")
    inter_rows = []
    buckets = lead_time_bucket(lead)
    for bucket in buckets.cat.categories:
        part = df[buckets == bucket]
        with_r = part[part["reminder_sent"]][config.LABEL].mean()
        without_r = part[~part["reminder_sent"]][config.LABEL].mean()
        inter_rows.append([bucket, _pct(without_r), _pct(with_r), f"−{(without_r - with_r) * 100:.1f} pts"])
    sections[-1] += (
        _table(["days ahead", "no reminder", "reminder", "reminder effect"], inter_rows)
        + """

A reminder barely matters for short-notice appointments and matters a lot for ones booked far ahead.
→ **One weight for `reminder_sent` cannot capture this. Engineer `reminder × lead time` (or use a
tree model, which finds interactions itself).**

### 6.3 Patient history: the hidden habit

"""
    )
    ratio = (df["prior_no_shows"] / df["prior_appointments"].replace(0, np.nan)).fillna(-1)
    ratio_bucket = pd.cut(
        ratio, bins=[-2, -0.5, 0.0001, 0.2, 0.4, 1.0], labels=["no history", "0%", "1–20%", "21–40%", "41–100%"]
    )
    sections[-1] += (
        _rate_table(df, ratio_bucket, "past no-show ratio")
        + """

Patients who missed often before miss more often now. The raw counts mix two things (how many visits,
how many misses); the **ratio** isolates the habit.
→ **Engineer `prior_no_show_rate = prior_no_shows / prior_appointments`** (0 when there is no history).
"""
    )
    for feature, order, title in [
        ("age_band", config.AGE_BANDS, "6.4 Age band"),
        ("visit_type", config.VISIT_TYPES, "6.5 Visit type"),
        ("booking_channel", config.BOOKING_CHANNELS, "6.6 Booking channel"),
        ("appointment_weekday", config.WEEKDAYS, "6.7 Weekday"),
    ]:
        sections[-1] += f"\n### {title}\n\n{_rate_table(df, feature, feature, order)}\n"
    distance_bucket = pd.cut(
        df["distance_km"],
        bins=[-0.1, 5, 10, 20, 40, 1000],
        labels=["0–5 km", "5–10 km", "10–20 km", "20–40 km", "40+ km"],
    )
    sections[-1] += (
        f"\n### 6.8 Distance (known values)\n\n{_rate_table(df[has_distance], distance_bucket[has_distance], 'distance')}\n"
    )
    sections[-1] += """
Smaller effects: telehealth lowers the rate, longer distance raises it, Friday and Monday are slightly
riskier, phone bookings slightly safer.
→ **Keep all of them. One-hot encode the categories.**"""

    # ---------------- 7. Relationships between features ----------------
    corr = df[config.NUMERIC_FEATURES].corr()
    corr_rows = [[a] + [f"{corr.loc[a, b]:+.2f}" for b in config.NUMERIC_FEATURES] for a in config.NUMERIC_FEATURES]
    strong = [
        (a, b, corr.loc[a, b])
        for i, a in enumerate(config.NUMERIC_FEATURES)
        for b in config.NUMERIC_FEATURES[i + 1 :]
        if abs(corr.loc[a, b]) >= 0.5
    ]
    strong_text = "; ".join(f"`{a}` ~ `{b}` ({r:+.2f})" for a, b, r in strong) or "none"
    sections.append(f"""## 7. Relationships between numeric features (Pearson correlation)

{_table(["", *config.NUMERIC_FEATURES], corr_rows)}

Pairs with |r| ≥ 0.5: {strong_text}.
`prior_no_shows` grows with `prior_appointments` by construction (you can only miss appointments you
had). That overlap is another reason to use the **ratio** from 6.3. No pair is so similar that one
must be dropped.""")

    # ---------------- 8. Leakage and split readiness ----------------
    scores = single_feature_auc(df)
    best_feature, best_score = max(scores.items(), key=lambda kv: kv[1])
    multi = (per_patient > 1).mean()
    sections.append(f"""## 8. Leakage and split readiness

**Single-feature check.** How well each feature *alone* separates no-shows (ROC-AUC; 0.50 = no
signal). A feature above {LEAKAGE_AUC:.2f} on its own would be suspicious: it usually means the column
encodes the answer.

{_table(["feature", "AUC alone"], [[f, f"{s:.3f}"] for f, s in sorted(scores.items(), key=lambda kv: -kv[1])])}

Strongest single feature: `{best_feature}` ({best_score:.3f}), {"**above the leakage threshold: investigate**" if best_score > LEAKAGE_AUC else "well below the leakage threshold"}.
Excluded from this table and from every model: `appointment_id`, `patient_id`, `{config.ORACLE}`.

**Patients repeat.** {_pct(multi)} of patients have more than one appointment (mean
{per_patient.mean():.2f}). If one patient's appointments landed in both train and test, the model
could score well by recognising the person rather than learning patterns.
→ **Step 3: split by patient (`GroupShuffleSplit` on `patient_id`), 60/20/20, so every patient is in
exactly one of train, validation or test.**""")

    # ---------------- 9. Bias ----------------
    sections.append(f"""## 9. Bias: age

{_rate_table(df, "age_band", "age band", config.AGE_BANDS)}

18–24-year-olds miss {_pct(young)} of appointments vs {_pct(old)} for 55–64, i.e.
{young / old:.1f}× as often. Any model trained on this data will flag younger patients more, including
young patients who would have attended (false positives).
→ **Step 5: report false-positive and false-negative rates per age band.** The output may only drive
supportive actions (an extra reminder), never penalties.""")

    # ---------------- 10. Decisions ----------------
    sections.append("""## 10. Decisions this analysis supports

| Finding | Decision | Step |
|---|---|---|
| 16% minority class | PR-AUC, ROC-AUC, Brier; threshold chosen on validation | 4–5 |
| `distance_km` 7.7% missing, at random | Median imputation fitted on train only + `distance_missing` flag | 3 |
| Patients repeat across rows | Split grouped by `patient_id`, 60/20/20 | 3 |
| Lead-time effect is a curve | Engineered `log(1 + lead_time_days)` | 4 |
| Reminder effect depends on lead time | Engineered `reminder × lead time`; tree model as comparison | 4 |
| Past behaviour predicts | Engineered `prior_no_show_rate` | 4 |
| No single feature is suspiciously strong | No leakage found in the features | 3 |
| Age bias | Per-age-band error rates; supportive use only | 5 |
""")
    return "\n\n".join(sections).rstrip() + "\n"


def main():
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(build_report(generate()))
    print(f"written to: {REPORT}")


if __name__ == "__main__":
    main()
