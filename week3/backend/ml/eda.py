"""Exploratory analysis of the synthetic dataset -> ml/reports/eda.md

    python -m ml.eda

Plain tables, no plotting dependency, so the report is reproducible and diffable in git.
"""

import pandas as pd

from . import config, data


def _table(frame: pd.DataFrame) -> str:
    cols = [str(c) for c in frame.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in frame.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def rate_by(df: pd.DataFrame, column) -> pd.DataFrame:
    g = df.groupby(column, observed=True)[config.TARGET].agg(n="size", no_show_rate="mean").reset_index()
    g["no_show_rate"] = g["no_show_rate"].round(3)
    return g


def report(df: pd.DataFrame) -> str:
    df = df.drop(columns=[data.TRUTH_COLUMN], errors="ignore")
    out = [
        "# EDA: synthetic appointment no-shows",
        "",
        "Generated by `python -m ml.eda`. Synthetic data (see docs/DATA_CARD.md).",
        "",
        f"**Shape:** {len(df)} rows × {df.shape[1]} columns · **patients:** {df.patient_ref.nunique()} "
        f"(median {df.patient_ref.value_counts().median():.0f} appointments each) · "
        f"**duplicate rows:** {int(df.drop(columns='appointment_id').duplicated().sum())}",
        "",
        "## Target balance",
        "",
        f"No-show rate **{df[config.TARGET].mean():.1%}**: imbalanced (about 1 in 6). Accuracy would be misleading "
        "(predicting 'shows up' for everyone is ~83% accurate), so models are compared on PR-AUC and ROC-AUC.",
        "",
        "## Missing values",
        "",
    ]
    missing = df.isna().sum()
    out.append(_table(pd.DataFrame({"column": missing.index, "missing": missing.values, "share": (missing / len(df)).round(3).values})[lambda f: f.missing > 0]))
    out += [
        "",
        "`distance_km` is missing for ~10% of rows, with the same no-show rate as rows that have it "
        f"({df[df.distance_km.isna()][config.TARGET].mean():.3f} vs {df[df.distance_km.notna()][config.TARGET].mean():.3f}): "
        "consistent with missing-at-random. Handled by **median imputation fitted on the training split only**, "
        "plus a was-missing indicator column.",
        "",
        "## Numeric summary",
        "",
    ]
    desc = df[["lead_time_days", "appointment_hour", "prior_appointments", "prior_no_shows", "distance_km"]].describe().T.round(2)
    out.append(_table(desc.reset_index().rename(columns={"index": "column"})))
    out += ["", "## No-show rate by feature", ""]
    for column in ["reminder_sent", "visit_type", "age_band", "appointment_weekday", "booking_channel"]:
        out += [f"**{column}**", "", _table(rate_by(df, column)), ""]

    lead_bucket = pd.cut(df.lead_time_days, [-1, 3, 7, 14, 30, 60, 180], labels=["0-3", "4-7", "8-14", "15-30", "31-60", "61+"])
    out += ["**lead_time_days (bucketed)**: rises steadily with wait. Under 0.5% of rows wait over 60 days, so "
            "`lead_time_capped` (cap at 60) stops those few extreme values dominating a linear model", "",
            _table(rate_by(df.assign(lead_time=lead_bucket), "lead_time")), ""]

    long_wait = df.lead_time_days > 30
    cross = (
        df.assign(wait=long_wait.map({True: "wait > 30 days", False: "wait ≤ 30 days"}))
        .pivot_table(index="wait", columns="reminder_sent", values=config.TARGET, aggfunc="mean").round(3)
        .reset_index().rename(columns={False: "no reminder", True: "reminder"})
    )
    out += ["**Wait × reminder**: the combination is worse than either alone → `long_wait_no_reminder`", "", _table(cross), ""]

    history = df.assign(rate=pd.cut(df.prior_no_shows / df.prior_appointments.where(df.prior_appointments > 0),
                                    [-0.01, 0, 0.25, 0.5, 1], labels=["0", "(0, .25]", "(.25, .5]", "(.5, 1]"]))
    history["rate"] = history["rate"].cat.add_categories("new patient").fillna("new patient")
    out += ["**Prior no-show rate**: a *rate* separates patients better than a raw count → `prior_no_show_rate`", "",
            _table(rate_by(history, "rate")), ""]

    distance = df.assign(km=pd.cut(df.distance_km, [0, 5, 10, 20, 500], labels=["≤5", "5-10", "10-20", "20+"]))
    cross = distance.pivot_table(index="km", columns="visit_type", values=config.TARGET, aggfunc="mean", observed=True).round(3).reset_index()
    out += ["**Distance × visit type**: flat up to 20 km; beyond that only in-person visits get worse → "
            "`in_person_distance_km` (a weak signal, kept because it is cheap and plausible)", "", _table(cross), ""]

    out += [
        "## Leakage check",
        "",
        "`checked_in` is recorded after the appointment and is the exact opposite of the target:",
        "",
        _table(pd.crosstab(df.checked_in, df[config.TARGET]).reset_index().rename(columns={0: "showed (0)", 1: "no-show (1)"})),
        "",
        "A model given this column would score ~1.0 and be useless before the visit. It is excluded "
        "(`EXCLUDED_COLUMNS` in `ml/features.py`, enforced by a test). `patient_ref` is excluded too and used "
        "only to keep each patient's appointments in a single split.",
        "",
    ]
    return "\n".join(out)


def main():
    df = data.generate()
    config.REPORT_DIR.mkdir(parents=True, exist_ok=True)
    (config.REPORT_DIR / "eda.md").write_text(report(df))
    print(f"wrote {config.REPORT_DIR / 'eda.md'}")


if __name__ == "__main__":
    main()
